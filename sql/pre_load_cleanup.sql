-- ============================================================================
-- SQL: pre_load_cleanup.sql
-- JIRA: GMRD-216
-- Author: GMRD Data Engineering
-- Description: Pre-load cleanup script executed before each daily batch.
--              Removes stale staging data and creates batch control entry.
--              Called by run_daily_batch.ksh before extract phase.
-- ============================================================================

-- Create batch control entry
INSERT INTO GMRD_CORE_DB.AUD_BATCH_CONTROL
(BATCH_ID, BATCH_NAME, BATCH_TYPE, SOURCE_SYSTEM, BUSINESS_DATE,
 START_TS, STATUS, CREATED_BY, CREATED_TS)
VALUES
(${BATCH_ID}, 'GMRD_DAILY_EOD', 'DAILY', 'ALL',
 CAST('${BUSINESS_DATE}' AS DATE FORMAT 'YYYY-MM-DD'),
 CURRENT_TIMESTAMP(6), 'RUNNING',
 SESSION, CURRENT_TIMESTAMP(6));

-- Clean staging tables for this business date (idempotent reload)
DELETE FROM GMRD_STG_DB.STG_TRADES_CALYPSO
WHERE TRADE_DATE = CAST('${BUSINESS_DATE}' AS DATE FORMAT 'YYYY-MM-DD');

DELETE FROM GMRD_STG_DB.STG_TRADES_MUREX
WHERE MX_TRADE_DATE = CAST('${BUSINESS_DATE}' AS DATE FORMAT 'YYYY-MM-DD');

DELETE FROM GMRD_STG_DB.STG_TRADES_SUMMIT
WHERE SMT_TRADE_DATE = CAST('${BUSINESS_DATE}' AS DATE FORMAT 'YYYY-MM-DD');

DELETE FROM GMRD_STG_DB.STG_POSITIONS_RAW
WHERE BUSINESS_DATE = CAST('${BUSINESS_DATE}' AS DATE FORMAT 'YYYY-MM-DD');

DELETE FROM GMRD_STG_DB.STG_MARKET_DATA_RAW
WHERE BUSINESS_DATE = CAST('${BUSINESS_DATE}' AS DATE FORMAT 'YYYY-MM-DD');

DELETE FROM GMRD_STG_DB.STG_COUNTERPARTY_RAW
WHERE BATCH_ID = ${BATCH_ID};

-- Purge staging data older than 3 business days
DELETE FROM GMRD_STG_DB.STG_TRADES_CALYPSO
WHERE TRADE_DATE < CAST('${BUSINESS_DATE}' AS DATE FORMAT 'YYYY-MM-DD') - INTERVAL '3' DAY;

DELETE FROM GMRD_STG_DB.STG_TRADES_MUREX
WHERE MX_TRADE_DATE < CAST('${BUSINESS_DATE}' AS DATE FORMAT 'YYYY-MM-DD') - INTERVAL '3' DAY;

DELETE FROM GMRD_STG_DB.STG_TRADES_SUMMIT
WHERE SMT_TRADE_DATE < CAST('${BUSINESS_DATE}' AS DATE FORMAT 'YYYY-MM-DD') - INTERVAL '3' DAY;

DELETE FROM GMRD_STG_DB.STG_POSITIONS_RAW
WHERE BUSINESS_DATE < CAST('${BUSINESS_DATE}' AS DATE FORMAT 'YYYY-MM-DD') - INTERVAL '3' DAY;
