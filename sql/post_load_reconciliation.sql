-- Reconcile Calypso trades: staging vs core
INSERT INTO GMRD_CORE_DB.AUD_RECONCILIATION
(RECON_NAME, RECON_TYPE, BUSINESS_DATE, SOURCE_SYSTEM, TARGET_SYSTEM,
 SOURCE_TABLE, TARGET_TABLE, METRIC_NAME,
 SOURCE_VALUE, TARGET_VALUE, DIFFERENCE,
 TOLERANCE_ABS, TOLERANCE_PCT, STATUS, BATCH_ID)
SELECT
    'TRADE_COUNT_CALYPSO',
    'ROW_COUNT',
    CAST('${BUSINESS_DATE}' AS DATE FORMAT 'YYYY-MM-DD'),
    'CALYPSO',
    'TERADATA',
    'STG_TRADES_CALYPSO',
    'TRD_TRADES',
    'TRADE_COUNT',
    stg.cnt,
    core.cnt,
    stg.cnt - COALESCE(core.cnt, 0),
    10.0,
    1.0,
    CASE WHEN ABS(stg.cnt - COALESCE(core.cnt, 0)) <= 10 THEN 'PASS' ELSE 'FAIL' END,
    ${BATCH_ID}
FROM (SELECT CAST(COUNT(*) AS DECIMAL(18,2)) AS cnt
      FROM GMRD_STG_DB.STG_TRADES_CALYPSO WHERE BATCH_ID = ${BATCH_ID}) stg
CROSS JOIN (SELECT CAST(COUNT(*) AS DECIMAL(18,2)) AS cnt
            FROM GMRD_CORE_DB.TRD_TRADES
            WHERE SOURCE_SYSTEM = 'CALYPSO' AND BATCH_ID = ${BATCH_ID} AND IS_CURRENT = 1) core;

