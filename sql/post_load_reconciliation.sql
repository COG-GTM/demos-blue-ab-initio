-- Reconcile market value totals
INSERT INTO GMRD_CORE_DB.AUD_RECONCILIATION
(RECON_NAME, RECON_TYPE, BUSINESS_DATE, SOURCE_SYSTEM, TARGET_SYSTEM,
 SOURCE_TABLE, TARGET_TABLE, METRIC_NAME,
 SOURCE_VALUE, TARGET_VALUE, DIFFERENCE,
 TOLERANCE_ABS, TOLERANCE_PCT, STATUS, BATCH_ID)
SELECT
    'MV_TOTAL_RECON',
    'VALUE_COMPARE',
    CAST('${BUSINESS_DATE}' AS DATE FORMAT 'YYYY-MM-DD'),
    'MULTI',
    'TERADATA',
    'STG_POSITIONS_RAW',
    'POS_DAILY_POSITIONS',
    'TOTAL_MARKET_VALUE_GBP',
    stg.mv,
    core.mv,
    stg.mv - COALESCE(core.mv, 0),
    1000000.00,
    0.01,
    CASE WHEN ABS(stg.mv - COALESCE(core.mv, 0)) <= 1000000.00 THEN 'PASS' ELSE 'WARNING' END,
    ${BATCH_ID}
FROM (SELECT CAST(SUM(MARKET_VALUE_BASE) AS DECIMAL(25,2)) AS mv
      FROM GMRD_STG_DB.STG_POSITIONS_RAW WHERE BATCH_ID = ${BATCH_ID}) stg
CROSS JOIN (SELECT CAST(SUM(MARKET_VALUE_GBP) AS DECIMAL(25,2)) AS mv
            FROM GMRD_CORE_DB.POS_DAILY_POSITIONS
            WHERE BUSINESS_DATE = CAST('${BUSINESS_DATE}' AS DATE FORMAT 'YYYY-MM-DD')
            AND BATCH_ID = ${BATCH_ID}) core;
